# ─── Command Router ─────────────────────────────────────

def handle_engineering_command(command: str) -> tuple[bool, bool, str]:
    """
    Route engineering-related commands.

    Returns:
        (handled, success, message)
    """
    cmd = command.lower().strip()

    # ─── Code Generation ────────────────────────
    if cmd.startswith("generate verilog ") or cmd.startswith("create verilog "):
        name = cmd.replace("generate verilog ", "").replace("create verilog ", "").strip()
        if not name:
            name = "my_module"
        name = name.replace(" ", "_")
        code = _generate_verilog_module(name)
        ok, msg = _save_generated_file(code, f"{name}.v")
        return True, ok, msg

    if cmd.startswith("generate testbench ") or cmd.startswith("create testbench "):
        name = cmd.replace("generate testbench ", "").replace("create testbench ", "").strip()
        if not name:
            name = "my_module"
        name = name.replace(" ", "_")
        code = _generate_verilog_testbench(name)
        ok, msg = _save_generated_file(code, f"{name}_tb.v")
        return True, ok, msg

    if cmd.startswith("generate vhdl ") or cmd.startswith("create vhdl "):
        name = cmd.replace("generate vhdl ", "").replace("create vhdl ", "").strip()
        if not name:
            name = "my_entity"
        name = name.replace(" ", "_")
        code = _generate_vhdl_entity(name)
        ok, msg = _save_generated_file(code, f"{name}.vhd")
        return True, ok, msg

    if cmd.startswith("generate arduino ") or cmd.startswith("create arduino "):
        name = cmd.replace("generate arduino ", "").replace("create arduino ", "").strip()
        if not name:
            name = "my_sketch"
        name = name.replace(" ", "_")
        code = _generate_arduino_sketch(name)
        ok, msg = _save_generated_file(code, f"{name}/{name}.ino")
        return True, ok, msg

    if cmd.startswith("generate esp32 ") or cmd.startswith("create esp32 "):
        name = cmd.replace("generate esp32 ", "").replace("create esp32 ", "").strip()
        if not name:
            name = "esp32_project"
        name = name.replace(" ", "_")
        code = _generate_esp32_sketch(name)
        ok, msg = _save_generated_file(code, f"{name}/{name}.ino")
        return True, ok, msg

    if cmd.startswith("generate stm32 ") or cmd.startswith("create stm32 "):
        name = cmd.replace("generate stm32 ", "").replace("create stm32 ", "").strip()
        if not name:
            name = "stm32_project"
        name = name.replace(" ", "_")
        code = _generate_stm32_main(name)
        ok, msg = _save_generated_file(code, f"{name}/main.c")
        return True, ok, msg

    # ─── Quick References ───────────────────────
    if cmd.startswith(("explain ", "what is a ", "what is ")):
        topic = (cmd.replace("explain ", "")
                 .replace("what is a ", "")
                 .replace("what is ", "").strip())
        ref = ENGINEERING_REFERENCES.get(topic)
        if ref:
            return True, True, ref

    # ─── Reference lookups ──────────────────────
    for topic, ref in ENGINEERING_REFERENCES.items():
        if topic in cmd and len(cmd) < 40:
            return True, True, ref

    return False, False, ""
